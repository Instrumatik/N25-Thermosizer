def t(key: str, **params: object) -> str:
    """Texto de interfaz en el idioma vigente; si no existe, usa el catálogo general."""
    pair = UI.get(key)
    if pair is None:
        return tr(key, STATE.language, **params)
    text = pair[0] if STATE.language is Language.ES else pair[1]
    return text.format(**params) if params else text


def enum_text(value: str) -> str:
    """Nombre legible de un valor de enumeración."""
    pair = ENUM_TEXT.get(value)
    if pair is None:
        return value
    return pair[0] if STATE.language is Language.ES else pair[1]
